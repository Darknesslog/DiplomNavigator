CREATE TABLE academic_periods (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY,
	name VARCHAR(100) NOT NULL,
	academic_year INTEGER NOT NULL,
	semester VARCHAR(16) NOT NULL,
	starts_on DATE NOT NULL,
	ends_on DATE NOT NULL,
	application_opens_at TIMESTAMP WITH TIME ZONE NOT NULL,
	application_closes_at TIMESTAMP WITH TIME ZONE NOT NULL,
	status VARCHAR(32) DEFAULT 'draft' NOT NULL,
	created_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL,
	updated_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL,
	CONSTRAINT pk_academic_periods PRIMARY KEY (id),
	CONSTRAINT uq_academic_periods_academic_year_semester UNIQUE (academic_year, semester),
	CONSTRAINT ck_academic_periods_dates_order CHECK (ends_on >= starts_on),
	CONSTRAINT ck_academic_periods_application_window CHECK (application_closes_at > application_opens_at),
	CONSTRAINT uq_academic_periods_name UNIQUE (name),
	CONSTRAINT ck_academic_periods_semester CHECK (semester IN ('autumn', 'spring')),
	CONSTRAINT ck_academic_periods_period_status CHECK (status IN ('draft', 'open', 'closed', 'archived'))
);

